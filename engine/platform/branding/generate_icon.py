"""Generate the temporary W placeholder; replace this artwork when a real brand exists.
Developer-only dependency: Pillow. No font files or third-party artwork are used.
Run from any directory: python engine/platform/branding/generate_icon.py
"""
from pathlib import Path
from io import BytesIO
import struct
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parent
sizes = (16, 24, 32, 48, 64, 128, 256)
# Neutral W built from a single polygon, normalized to a 256px viewBox.
points = [(44,65),(71,65),(90,153),(115,83),(141,83),(166,153),(185,65),
          (212,65),(181,191),(155,191),(128,119),(101,191),(75,191)]
source = Image.new('RGBA', (1024,1024))
draw = ImageDraw.Draw(source)
draw.rounded_rectangle((16,16,1008,1008), radius=192, fill=(30,42,56,255))
draw.polygon([(x*4,y*4) for x,y in points], fill=(225,235,246,255))
images = [source.resize((n,n),Image.Resampling.LANCZOS) for n in sizes]
blobs=[]
for image in images:
    data=BytesIO();image.save(data,format='PNG');blobs.append(data.getvalue())
# All seven PNG-compressed RGBA frames are retained in the Windows ICO.
header=struct.pack('<HHH',0,1,len(sizes));entries=b'';payload=b'';offset=6+16*len(sizes)
for n,data in zip(sizes,blobs):
    entries+=struct.pack('<BBBBHHII',n%256,n%256,0,0,1,32,len(data),offset)
    payload+=data;offset+=len(data)
(root/'WhispEngine.ico').write_bytes(header+entries+payload)
lines=['// Generated by generate_icon.py. TEMPORARY W PLACEHOLDER, not a final logo.',
       '#pragma once','#include <cstddef>','namespace whisp::branding {']
for n,data in zip(sizes,blobs):
    lines.append(f'inline constexpr unsigned char Icon{n}[]={{')
    lines.extend('    '+','.join(str(v) for v in data[i:i+24])+',' for i in range(0,len(data),24))
    lines.append('};')
lines+=['struct IconFrame { const unsigned char* png; std::size_t bytes; };',
        'inline constexpr IconFrame WindowIcons[]={']
lines += [f'    {{Icon{n},sizeof(Icon{n})}},' for n in sizes]
lines+=['};','}']
(root/'GeneratedIcon.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
images[-1].save(root/'WhispEngine-placeholder.png')
print('Generated ICO and embedded RGBA PNG frames:',sizes)
